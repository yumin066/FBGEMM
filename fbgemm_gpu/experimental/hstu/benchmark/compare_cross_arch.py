#!/usr/bin/env python3
"""
Compare cross-architecture HSTU benchmark CSVs.

Reads one or more CSV files generated by bench_hstu_cross_arch.py and prints a
TFLOPS comparison table using Ampere BF16 as the baseline.

Usage:
  python compare_cross_arch.py --dir 6cross_bench_results
  python compare_cross_arch.py 6cross_bench_results/*.csv
  python compare_cross_arch.py --dir 6cross_bench_results --baseline path/to/a100.csv
"""

import argparse
import csv
import glob
import os
import re
import sys
from dataclasses import dataclass
from typing import Dict, List, Optional, Sequence, Tuple


CONFIG_RE = re.compile(r"bs=(\d+)\s+seq=(\d+)\s+h=(\d+)\s+(full|causal)$")


@dataclass
class CsvRun:
    path: str
    gpu_name: str
    short_name: str
    is_ampere: bool
    rows: Dict[str, Dict[str, str]]


def canonical_gpu_name(gpu_name: str) -> str:
    name = " ".join(gpu_name.strip().split())
    upper = name.upper()
    if "RTX PRO 6000" in upper and "BLACKWELL" in upper:
        return "RTX6K"
    if "H200" in upper:
        return "H200"
    if "H100" in upper:
        return "H100"
    if "A100" in upper:
        return "A100"
    if "A40" in upper:
        return "A40"
    if "A30" in upper:
        return "A30"
    if "A10" in upper:
        return "A10"
    if "L40S" in upper:
        return "L40S"
    if "L40" in upper:
        return "L40"
    if "V100" in upper:
        return "V100"
    stripped = re.sub(r"^NVIDIA\s+", "", name, flags=re.IGNORECASE)
    return re.sub(r"\s+", "_", stripped.strip()) or "unknown"


def is_ampere_gpu(gpu_name: str) -> bool:
    upper = gpu_name.upper()
    return any(token in upper for token in ("A100", "A30", "A10", "A40"))


def parse_float(value: str) -> Optional[float]:
    value = (value or "").strip()
    if not value:
        return None
    try:
        return float(value)
    except ValueError:
        return None


def parse_config_key(config: str) -> Tuple[int, int, int, str]:
    match = CONFIG_RE.match(config.strip())
    if not match:
        return (sys.maxsize, sys.maxsize, sys.maxsize, config)
    bs, seq, heads, mask = match.groups()
    return (int(bs), int(seq), int(heads), mask)


def discover_csv_paths(paths: Sequence[str], directory: Optional[str]) -> List[str]:
    seen: set = set()
    resolved: List[str] = []
    if directory:
        for path in sorted(glob.glob(os.path.join(directory, "*.csv"))):
            abspath = os.path.abspath(path)
            if abspath not in seen:
                seen.add(abspath)
                resolved.append(abspath)
    for path in paths:
        abspath = os.path.abspath(path)
        if abspath not in seen:
            seen.add(abspath)
            resolved.append(abspath)
    return resolved


def load_csv_run(path: str) -> CsvRun:
    with open(path, newline="") as f:
        reader = csv.DictReader(f)
        fieldnames = reader.fieldnames or []
        if "config" not in fieldnames:
            raise ValueError(f"{path}: missing required 'config' column")
        if "gpu_name" not in fieldnames:
            raise ValueError(f"{path}: missing required 'gpu_name' column")
        rows: Dict[str, Dict[str, str]] = {}
        gpu_names: set = set()
        for row in reader:
            config = (row.get("config") or "").strip()
            if not config:
                continue
            gpu_name = (row.get("gpu_name") or "").strip()
            if gpu_name:
                gpu_names.add(gpu_name)
            rows[config] = row

    if not rows:
        raise ValueError(f"{path}: no benchmark rows found")
    if not gpu_names:
        raise ValueError(f"{path}: all rows are missing gpu_name")
    if len(gpu_names) != 1:
        raise ValueError(
            f"{path}: expected a single gpu_name, found {sorted(gpu_names)}"
        )

    gpu_name = next(iter(gpu_names))
    return CsvRun(
        path=os.path.abspath(path),
        gpu_name=gpu_name,
        short_name=canonical_gpu_name(gpu_name),
        is_ampere=is_ampere_gpu(gpu_name),
        rows=rows,
    )


def make_unique_names(runs: Sequence[CsvRun]) -> None:
    """Append #N suffix when multiple runs share the same short GPU name."""
    counts: Dict[str, int] = {}
    for run in runs:
        counts[run.short_name] = counts.get(run.short_name, 0) + 1
    used: Dict[str, int] = {}
    for run in runs:
        if counts[run.short_name] == 1:
            continue
        used[run.short_name] = used.get(run.short_name, 0) + 1
        run.short_name = f"{run.short_name}#{used[run.short_name]}"


def pick_baseline(runs: Sequence[CsvRun], baseline_path: Optional[str]) -> CsvRun:
    if baseline_path:
        wanted = os.path.abspath(baseline_path)
        for run in runs:
            if run.path == wanted:
                return run
        raise ValueError(f"--baseline file not found in inputs: {wanted}")
    ampere_runs = [run for run in runs if run.is_ampere]
    if not ampere_runs:
        raise ValueError(
            "No Ampere baseline detected. Pass an Ampere CSV or use --baseline PATH."
        )
    return sorted(ampere_runs, key=lambda r: (r.short_name, r.path))[0]


def fmt_tflops(value: Optional[float]) -> str:
    return "N/A" if value is None else f"{value:.1f}"


def fmt_speedup(value: Optional[float], baseline: Optional[float]) -> str:
    if value is None or baseline is None or baseline == 0.0:
        return "N/A"
    return f"{value / baseline - 1.0:+.1%}"


def build_table(
    runs: Sequence[CsvRun], baseline: CsvRun
) -> Tuple[List[str], List[List[str]]]:
    configs = sorted(
        {config for run in runs for config in run.rows},
        key=parse_config_key,
    )

    other_runs = sorted(
        [run for run in runs if run.path != baseline.path],
        key=lambda r: (r.short_name, r.path),
    )

    headers = ["Config", f"{baseline.short_name} BF16"]
    for run in other_runs:
        headers += [f"{run.short_name} BF16", "vs baseline"]
        if any(parse_float(row.get("fp8_tflops", "")) is not None
               for row in run.rows.values()):
            headers += [f"{run.short_name} FP8", "vs baseline"]

    table_rows: List[List[str]] = []
    for config in configs:
        base_bf16 = parse_float(
            baseline.rows.get(config, {}).get("bf16_tflops", "")
        )
        row: List[str] = [config, fmt_tflops(base_bf16)]
        for run in other_runs:
            entry = run.rows.get(config, {})
            bf16 = parse_float(entry.get("bf16_tflops", ""))
            row += [fmt_tflops(bf16), fmt_speedup(bf16, base_bf16)]
            if any(parse_float(r.get("fp8_tflops", "")) is not None
                   for r in run.rows.values()):
                fp8 = parse_float(entry.get("fp8_tflops", ""))
                row += [fmt_tflops(fp8), fmt_speedup(fp8, base_bf16)]
        table_rows.append(row)

    return headers, table_rows


def print_table(headers: Sequence[str], rows: Sequence[Sequence[str]]) -> None:
    widths = [len(h) for h in headers]
    for row in rows:
        for i, cell in enumerate(row):
            widths[i] = max(widths[i], len(cell))

    def fmt_row(row: Sequence[str]) -> str:
        parts = [
            cell.ljust(widths[i]) if i == 0 else cell.rjust(widths[i])
            for i, cell in enumerate(row)
        ]
        return " | ".join(parts)

    print(fmt_row(headers))
    print("-+-".join("-" * w for w in widths))
    for row in rows:
        print(fmt_row(row))


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Cross-architecture HSTU speedup comparison (baseline: Ampere BF16)",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    parser.add_argument("csv_files", nargs="*", metavar="CSV",
                        help="Benchmark CSV files to compare")
    parser.add_argument("--dir", type=str, default=None,
                        metavar="DIR", help="Directory to scan for *.csv files")
    parser.add_argument("--baseline", type=str, default=None,
                        metavar="PATH",
                        help="Explicit baseline CSV (overrides Ampere auto-detection)")
    parser.add_argument("--out", type=str, default=None,
                        metavar="PATH",
                        help="Save comparison table to this file (default: auto-named in --dir)")
    args = parser.parse_args()

    csv_paths = discover_csv_paths(args.csv_files, args.dir)
    if not csv_paths:
        sys.exit("ERROR: No CSV files found. Pass files directly or use --dir DIR.")

    try:
        runs = [load_csv_run(path) for path in csv_paths]
        make_unique_names(runs)
        baseline = pick_baseline(runs, args.baseline)
    except ValueError as exc:
        sys.exit(f"ERROR: {exc}")

    headers, rows = build_table(runs, baseline)

    lines = []
    lines.append(f"Baseline : {baseline.short_name}  ({baseline.gpu_name})")
    lines.append(f"Source   : {baseline.path}")
    lines.append("")

    widths = [len(h) for h in headers]
    for row in rows:
        for i, cell in enumerate(row):
            widths[i] = max(widths[i], len(cell))

    def fmt_row(row):
        parts = [
            cell.ljust(widths[i]) if i == 0 else cell.rjust(widths[i])
            for i, cell in enumerate(row)
        ]
        return " | ".join(parts)

    lines.append(fmt_row(headers))
    lines.append("-+-".join("-" * w for w in widths))
    for row in rows:
        lines.append(fmt_row(row))
    lines.append("")

    output = "\n".join(lines)
    print(output)

    # Determine output path
    out_path = args.out
    if out_path is None:
        commit = (
            os.popen("git rev-parse --short HEAD 2>/dev/null").read().strip()
            or "unknown"
        )
        timestamp = __import__("datetime").datetime.now().strftime("%Y%m%d_%H%M")
        out_dir = args.dir if args.dir else os.path.dirname(csv_paths[0])
        out_path = os.path.join(out_dir, f"compare_{commit}_{timestamp}.txt")

    with open(out_path, "w") as f:
        f.write(output)
    print(f"Saved → {out_path}")


if __name__ == "__main__":
    main()
